/**
 * Get questions filtered by category and relationship mode.
 * @param {string} category - 'basics' | 'relationship' | 'personality' | 'deep' | 'mix'
 * @param {string} relationshipType - 'couple' | 'friends' | 'family' | 'other'
 * @param {number} count - Number of questions to return
 * @returns {Question[]}
 */
export function getQuestions(category, relationshipType, count = 10) {
  const modeMap = {
    couple: 'couple',
    friends: 'friends',
    family: 'family',
    other: 'all',
  };
  const mode = modeMap[relationshipType] || 'all';

  let filtered;
  if (category === 'mix') {
    filtered = questions.filter(
      (q) => q.mode === 'all' || q.mode === mode
    );
  } else {
    filtered = questions.filter(
      (q) => q.category === category && (q.mode === 'all' || q.mode === mode)
    );
  }

  // Shuffle using Fisher-Yates
  const shuffled = [...filtered];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled.slice(0, count);
}
